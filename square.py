def area(a):
    """
    Вычисляет площадь квадрата.

    Аргументы:
        a (float): длина стороны квадрата.

    Возвращает:
        float: площадь квадрата.

    Пример вызова:
        >>> area(4)
        16
    """
    return a ** 2


def perimeter(a):
    """
    Вычисляет периметр квадрата.

    Аргументы:
        a (float): длина стороны квадрата.

    Возвращает:
        float: периметр квадрата.

    Пример вызова:
        >>> perimeter(4)
        16
    """
    return 4 * a
